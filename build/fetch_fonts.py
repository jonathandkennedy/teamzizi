"""Download the brand webfonts for self-hosting and emit fonts.css.

Both families are SIL Open Font License, so self-hosting and redistribution
are permitted. Self-hosting rather than linking Google Fonts removes a
third-party render-blocking request from the critical path and, more to the
point, removes a dependency the client cannot control — which is the whole
premise of this rebuild.

Run once; the woff2 files and fonts.css are committed.

    python3 build/fetch_fonts.py
"""

from __future__ import annotations

import re
import sys
import urllib.request
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "site" / "assets" / "fonts"
CSS = Path(__file__).resolve().parent.parent / "site" / "assets" / "css" / "fonts.css"

# A modern desktop UA is required or Google serves ttf instead of woff2.
UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
)

# Reem Kufi Fun ships at weight 400 only — design.md is explicit that every
# heading renders at 400, and it is the single most recognisable brand asset.
# Lato carries body (400) and the uppercase tracked UI (700).
WANT = [
    ("Reem Kufi Fun", "reem-kufi-fun", [400]),
    ("Lato", "lato", [400, 700]),
]

SUBSETS = {"latin": "", "latin-ext": "-ext"}

FACE = re.compile(
    r"/\*\s*(?P<subset>[\w-]+)\s*\*/\s*@font-face\s*\{(?P<body>[^}]*)\}",
    re.DOTALL,
)


def fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read()


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    blocks: list[str] = [
        "/* Self-hosted brand webfonts — SIL Open Font License.",
        " * Generated by build/fetch_fonts.py; do not edit by hand.",
        " */",
        "",
    ]

    for family, slug, weights in WANT:
        query = family.replace(" ", "+")
        css_url = (
            f"https://fonts.googleapis.com/css2?family={query}:wght@"
            + ";".join(str(w) for w in weights)
            + "&display=swap"
        )
        css = fetch(css_url).decode("utf-8")

        for match in FACE.finditer(css):
            subset = match.group("subset")
            if subset not in SUBSETS:
                continue
            body = match.group("body")

            weight_match = re.search(r"font-weight:\s*(\d+)", body)
            src_match = re.search(r"url\((https://[^)]+\.woff2)\)", body)
            range_match = re.search(r"unicode-range:\s*([^;]+);", body)
            if not (weight_match and src_match and range_match):
                continue

            weight = int(weight_match.group(1))
            if weight not in weights:
                continue

            filename = f"{slug}-{weight}{SUBSETS[subset]}.woff2"
            data = fetch(src_match.group(1))
            (OUT / filename).write_bytes(data)
            print(f"  {filename}  {len(data) / 1024:.1f} KB  ({subset})")

            blocks.append(
                "@font-face {\n"
                f"  font-family: '{family}';\n"
                "  font-style: normal;\n"
                f"  font-weight: {weight};\n"
                "  font-display: swap;\n"
                f"  src: url('/assets/fonts/{filename}') format('woff2');\n"
                f"  unicode-range: {range_match.group(1).strip()};\n"
                "}\n"
            )

    CSS.write_text("\n".join(blocks), encoding="utf-8")
    print(f"\nwrote {CSS.relative_to(CSS.parent.parent.parent.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
